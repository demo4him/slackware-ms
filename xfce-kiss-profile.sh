#!/bin/bash
# XFCE KISS Profile Builder
# Run on the current installation. It creates one portable, self-extracting
# restore script containing the user's XFCE configuration and personal assets.

set -Eeuo pipefail

PROFILE_NAME="XFCE-KISS-$(date +%Y%m%d)"
OUTPUT="${1:-$PWD/${PROFILE_NAME}-restore.sh}"
HOME_DIR="${HOME:?HOME is not set}"

if [[ $(id -u) -eq 0 ]]; then
    echo "Run this script as your normal desktop user, not as root." >&2
    exit 1
fi

if ! command -v tar >/dev/null 2>&1; then
    echo "Required command not found: tar" >&2
    exit 1
fi
if ! command -v base64 >/dev/null 2>&1; then
    echo "Required command not found: base64" >&2
    exit 1
fi

WORK=$(mktemp -d "${TMPDIR:-/tmp}/xfce-kiss.XXXXXX")
trap 'rm -rf "$WORK"' EXIT
STAGE="$WORK/payload"
mkdir -p "$STAGE"

# User configuration and assets. Missing paths are simply skipped.
ITEMS=(
    .config/xfce4
    .config/gtk-2.0
    .config/gtk-3.0
    .config/gtk-4.0
    .config/Thunar
    .config/xfce4-terminal
    .config/autostart
    .config/menus
    .gtkrc-2.0
    .gtkrc-2.0-kde
    .themes
    .icons
    .fonts
    .local/share/themes
    .local/share/icons
    .local/share/fonts
    .local/share/backgrounds
    .local/share/applications
    .local/share/xfce4
)

COPIED=()
for item in "${ITEMS[@]}"; do
    if [[ -e "$HOME_DIR/$item" || -L "$HOME_DIR/$item" ]]; then
        mkdir -p "$STAGE/$(dirname "$item")"
        cp -a "$HOME_DIR/$item" "$STAGE/$item"
        COPIED+=("$item")
    fi
done

# Keep a readable inventory of relevant Slackware packages for reinstall planning.
mkdir -p "$STAGE/.local/share/xfce4-profiles/$PROFILE_NAME"
INFO_DIR="$STAGE/.local/share/xfce4-profiles/$PROFILE_NAME"
cat > "$INFO_DIR/PROFILE-INFO.txt" <<EOF
XFCE KISS PROFILE
Profile: $PROFILE_NAME
Created: $(date)
Source host: $(hostname)
Source user: $USER

Included user paths:
$(printf ' - %s\n' "${COPIED[@]}")

This profile restores user configuration and user-installed themes/assets.
It does not install Slackware packages or system-wide themes, fonts, drivers,
or applications. Review XFCE-PACKAGES.txt when preparing the new installation.
For best results, install the same XFCE panel plugins and applications first.
Run the restore script as the target desktop user, not as root.
EOF

if [[ -d /var/log/packages ]]; then
    find /var/log/packages -maxdepth 1 -type f -printf '%f\n' \
      | grep -Ei '(^|[-])(xfce|xfwm|xfconf|exo|garcon|thunar|tumbler|gtk|catppuccin|ristretto|mousepad|orage)([-]|$)' \
      | sort > "$INFO_DIR/XFCE-PACKAGES.txt" || true
else
    : > "$INFO_DIR/XFCE-PACKAGES.txt"
fi

ARCHIVE="$WORK/profile.tar.gz"
tar -czf "$ARCHIVE" -C "$STAGE" .

mkdir -p "$(dirname "$OUTPUT")"
cat > "$OUTPUT" <<'RESTORE_HEADER'
#!/bin/bash
# XFCE KISS self-contained profile restore script.
# Generated by XFCE KISS Profile Builder.
set -Eeuo pipefail

if [[ $(id -u) -eq 0 ]]; then
    echo "Run this script as your normal desktop user, not as root." >&2
    exit 1
fi

if ! command -v tar >/dev/null 2>&1 || ! command -v base64 >/dev/null 2>&1; then
    echo "Required commands not found: tar and/or base64" >&2
    exit 1
fi

HOME_DIR="${HOME:?HOME is not set}"
BACKUP="$HOME_DIR/.xfce-kiss-before-restore-$(date +%Y%m%d-%H%M%S)"
mkdir -p "$BACKUP"

# Back up existing configuration before replacing it.
for item in .config/xfce4 .config/gtk-2.0 .config/gtk-3.0 .config/gtk-4.0 \
            .config/Thunar .config/xfce4-terminal .config/autostart \
            .config/menus .gtkrc-2.0 .gtkrc-2.0-kde .themes .icons .fonts \
            .local/share/themes .local/share/icons .local/share/fonts \
            .local/share/backgrounds .local/share/applications .local/share/xfce4; do
    if [[ -e "$HOME_DIR/$item" || -L "$HOME_DIR/$item" ]]; then
        mkdir -p "$BACKUP/$(dirname "$item")"
        cp -a "$HOME_DIR/$item" "$BACKUP/$item"
    fi
done

echo "Existing XFCE configuration backed up to: $BACKUP"
echo "Restoring profile into: $HOME_DIR"

# Stop the panel and settings daemon if they are running; they will restart
# at the next login and read the restored configuration.
if command -v xfce4-panel >/dev/null 2>&1; then
    xfce4-panel --quit >/dev/null 2>&1 || true
fi
if command -v xfconf-query >/dev/null 2>&1; then
    xfconf-query --shutdown >/dev/null 2>&1 || true
fi

ARCHIVE_LINE=$(awk '/^__XFCE_PROFILE_ARCHIVE_BELOW__$/ { print NR + 1; exit }' "$0")
if [[ -z "${ARCHIVE_LINE:-}" ]]; then
    echo "Embedded profile archive not found; this file may be damaged." >&2
    exit 1
fi

PAYLOAD_TMP=$(mktemp "${TMPDIR:-/tmp}/xfce-kiss-restore.XXXXXX.tar.gz")
trap 'rm -f "$PAYLOAD_TMP"' EXIT
tail -n +"$ARCHIVE_LINE" "$0" | base64 -d > "$PAYLOAD_TMP"
tar -xzf "$PAYLOAD_TMP" -C "$HOME_DIR"
rm -f "$PAYLOAD_TMP"
trap - EXIT

# Ensure restored files belong to the current user.
chown -R "$(id -u):$(id -g)" "$HOME_DIR/.config/xfce4" \
    "$HOME_DIR/.config/gtk-2.0" "$HOME_DIR/.config/gtk-3.0" \
    "$HOME_DIR/.config/gtk-4.0" "$HOME_DIR/.config/Thunar" \
    "$HOME_DIR/.config/xfce4-terminal" "$HOME_DIR/.config/autostart" \
    "$HOME_DIR/.config/menus" "$HOME_DIR/.themes" "$HOME_DIR/.icons" \
    "$HOME_DIR/.fonts" "$HOME_DIR/.local/share/themes" \
    "$HOME_DIR/.local/share/icons" "$HOME_DIR/.local/share/fonts" \
    "$HOME_DIR/.local/share/backgrounds" "$HOME_DIR/.local/share/applications" \
    "$HOME_DIR/.local/share/xfce4" 2>/dev/null || true

# Restore GTK rc files separately (chown above is for directories).
for f in "$HOME_DIR/.gtkrc-2.0" "$HOME_DIR/.gtkrc-2.0-kde"; do
    [[ ! -e "$f" ]] || chown "$(id -u):$(id -g)" "$f"
done

# Start a fresh panel process. Do not use --restart here: that option
# talks to the panel over D-Bus and can show an error if no panel service
# is registered yet (for example, immediately after --quit).
if command -v xfce4-panel >/dev/null 2>&1; then
    sleep 1
    nohup xfce4-panel >/dev/null 2>&1 </dev/null &
fi

echo
echo "XFCE KISS profile restored successfully."
echo "Log out and log back in (or reboot) to apply all settings."
echo "A pre-restore backup is available at: $BACKUP"
echo "Package inventory: $HOME_DIR/.local/share/xfce4-profiles/"
exit 0

__XFCE_PROFILE_ARCHIVE_BELOW__
RESTORE_HEADER

base64 < "$ARCHIVE" >> "$OUTPUT"
chmod 755 "$OUTPUT"

# Validate that the generated file is plain ASCII and contains the archive marker.
if LC_ALL=C grep -q '[^ -~]' "$OUTPUT"; then
    echo "Generated restore script is not plain ASCII." >&2
    exit 1
fi
if ! grep -aq '^__XFCE_PROFILE_ARCHIVE_BELOW__$' "$OUTPUT" || [[ ! -s "$OUTPUT" ]]; then
    echo "Failed to validate generated restore script." >&2
    exit 1
fi

echo
echo "XFCE KISS profile bundle created:"
echo "  $OUTPUT"
echo "Size: $(du -h "$OUTPUT" | awk '{print $1}')"
echo
echo "The embedded archive is Base64 encoded, so the restore script remains plain ASCII."
echo "Copy this single .sh file to your new Slackware installation."
echo "Run it as the normal desktop user (not root), then log out and back in."
echo "Note: Slackware packages and system-wide themes/plugins are listed or documented,"
echo "but are not automatically installed by this user-profile restore bundle."
